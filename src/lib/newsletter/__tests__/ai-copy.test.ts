import { describe, expect, it } from "vitest";
import { __cleanForTest as clean } from "@/lib/newsletter/ai-copy";

/**
 * Οι ετικέτες που διαρρέει το μοντέλο. Όλες οι περιπτώσεις εδώ παρατηρήθηκαν σε
 * πραγματική εκτέλεση — δεν είναι υποθετικές.
 */
describe("καθαρισμός γραμμής", () => {
  it("κόβει ετικέτα με επιπλέον λέξη", () => {
    expect(clean("Θέμα email: Εργαλεία KNIPEX που αντέχουν")).toBe("Εργαλεία KNIPEX που αντέχουν");
    expect(clean("Τίτλος hero: Η αντοχή που χρειάζεσαι")).toBe("Η αντοχή που χρειάζεσαι");
    expect(clean("Επικεφαλίδα: ΕΡΓΑΛΕΙΑ ΓΙΑ ΚΑΘΕ ΜΕΡΑ")).toBe("ΕΡΓΑΛΕΙΑ ΓΙΑ ΚΑΘΕ ΜΕΡΑ");
    expect(clean("Κείμενο: Επιλεγμένα KNIPEX σε τιμές")).toBe("Επιλεγμένα KNIPEX σε τιμές");
  });

  it("κόβει αρίθμηση και εισαγωγικά", () => {
    expect(clean('3. «Δύο εργαλεία, μία τιμή»')).toBe("Δύο εργαλεία, μία τιμή");
    expect(clean('- "Προσφορά Σεπτεμβρίου"')).toBe("Προσφορά Σεπτεμβρίου");
  });

  /** Πραγματικό κείμενο με άνω κάτω τελεία ΔΕΝ είναι ετικέτα. */
  it("δεν κόβει νόμιμο κείμενο", () => {
    expect(clean("Προσοχή: η προσφορά λήγει στις 30.09")).toBe("Προσοχή: η προσφορά λήγει στις 30.09");
    expect(clean("KNIPEX Cobra: η γκαζοτανάλια που κρατά")).toBe("KNIPEX Cobra: η γκαζοτανάλια που κρατά");
  });
});

import { __fixBrandsForTest as fixBrands } from "@/lib/newsletter/ai-copy";

/**
 * Το μοντέλο έγραψε «ΚΝΙΡΕΧ» αντί για «KNIPEX» — ελληνικά γράμματα που μοιάζουν
 * οπτικά με λατινικά. Παρατηρήθηκε σε πραγματική εκτέλεση.
 */
describe("ονόματα μαρκών σε λατινικά", () => {
  it("επαναφέρει μάρκα γραμμένη με ελληνικούς ομοιογλύφους", () => {
    expect(fixBrands("ΚΝΙΡΕΧ που δουλεύουν κάθε μέρα", ["KNIPEX"])).toBe(
      "KNIPEX που δουλεύουν κάθε μέρα",
    );
    expect(fixBrands("Εργαλεία ΜΕΡΑ και ΚΝΙΡΕΧ", ["KNIPEX"])).toBe("Εργαλεία ΜΕΡΑ και KNIPEX");
  });

  /** Κανονικές ελληνικές λέξεις ΔΕΝ πειράζονται — μόνο ό,τι ταιριάζει σε γνωστή μάρκα. */
  it("αφήνει άθικτο το ελληνικό κείμενο", () => {
    expect(fixBrands("ΕΡΓΑΛΕΙΑ ΓΙΑ ΚΑΘΕ ΜΕΡΑ", ["KNIPEX"])).toBe("ΕΡΓΑΛΕΙΑ ΓΙΑ ΚΑΘΕ ΜΕΡΑ");
    expect(fixBrands("ΝΑΙ ΟΧΙ ΤΟΤΕ", ["KNIPEX", "WERA"])).toBe("ΝΑΙ ΟΧΙ ΤΟΤΕ");
  });

  it("δεν αλλάζει τίποτα χωρίς μάρκες", () => {
    expect(fixBrands("ΚΝΙΡΕΧ", [])).toBe("ΚΝΙΡΕΧ");
  });
});
