export type AngleId = (typeof ANGLES)[number]["id"];

export type GeneratedCopy = {
  subject: string;
  preheader: string;
  eyebrow: string;
  title: string;
  text: string;
};

/**
 * Τι ξέρουμε πραγματικά για την καμπάνια, σε μορφή που διαβάζει το μοντέλο.
 *
 * ΜΟΝΟ μετρημένα στοιχεία: μάρκες, πλήθος, εύρος τιμών, ποσοστά, ημερομηνία.
 * Ό,τι δεν είναι εδώ, το μοντέλο δεν μπορεί να το επικαλεστεί — και αυτός είναι
 * ο μόνος τρόπος να μη γράψει «αποκλειστικά για εσάς» ή «μοναδική ευκαιρία»,
 * που είναι ισχυρισμοί χωρίς πηγή.
 */
function brief(products: PickedProduct[], validUntil: string): string {
  if (products.length === 0) {
    return "Καμία επιλογή προϊόντων ακόμη — γράψε γενικό μήνυμα προσφορών χωρίς να επικαλεστείς συγκεκριμένα προϊόντα ή ποσοστά.";
  }

  const brands = [...new Set(products.map((p) => p.brand).filter(Boolean))];
  const discounts = products.map((p) => Number(p.discount)).filter((n) => Number.isFinite(n) && n > 0);
  const prices = products
    .map((p) => Number(p.price.replace(/[^\d,]/g, "").replace(",", ".")))
    .filter((n) => Number.isFinite(n) && n > 0);

  const lines = [
    `Προϊόντα στην καμπάνια: ${products.length}`,
    brands.length ? `Μάρκες: ${brands.join(", ")}` : "",
    discounts.length
      ? `Εκπτώσεις: από ${Math.min(...discounts)}% έως ${Math.max(...discounts)}%`
      : "Δεν υπάρχουν δηλωμένες εκπτώσεις — ΜΗΝ αναφέρεις ποσοστό.",
    prices.length
      ? `Τιμές: ${Math.min(...prices).toFixed(2)} € έως ${Math.max(...prices).toFixed(2)} € με ΦΠΑ`
      : "",
    validUntil ? `Ισχύει έως: ${validUntil}` : "Δεν έχει οριστεί ημερομηνία λήξης — ΜΗΝ αναφέρεις προθεσμία.",
    `Παραδείγματα: ${products.slice(0, 4).map((p) => p.name).join(" · ")}`,
  ].filter(Boolean);

  return lines.join("\n");
}

/** Κόβει εισαγωγικά, αρίθμηση και ετικέτες που βάζει το μοντέλο παρά τις οδηγίες. */
function clean(line: string): string {
  return line
    .replace(/^\s*[-•*\d]+[.)]?\s*/, "")
    .replace(/^(ΘΕΜΑ|PREHEADER|ΕΠΙΚΕΦΑΛΙΔΑ|ΤΙΤΛΟΣ|ΚΕΙΜΕΝΟ)\s*[:：]\s*/i, "")
    .replace(/^["'«»]+|["'«»]+$/g, "")
    .trim();
}

export async function generateCampaignCopy(input: {
  angle: AngleId;
  products: PickedProduct[];
  validUntil: string;
}): Promise<GeneratedCopy> {
  const angle = ANGLES.find((a) => a.id === input.angle) ?? ANGLES[0];

  const system = [
    "Είσαι copywriter για ελληνικό e-shop επαγγελματικών εργαλείων (Kolleris, Πειραιάς, από το 1978).",
    "Κοινό: τεχνίτες, συνεργεία, ναυπηγεία, εργοστάσια, υπεύθυνοι προμηθειών. Δουλεύουν με τα χέρια τους και δεν έχουν χρόνο για διαφήμιση.",
    "ΥΦΟΣ: άμεσο και συγκεκριμένο. ΧΩΡΙΣ θαυμαστικά. ΧΩΡΙΣ emoji. ΧΩΡΙΣ «ανακαλύψτε», «μοναδική ευκαιρία», «απίστευτες τιμές».",
    "ΜΗΝ επινοείς αριθμούς, ποσοστά, ημερομηνίες ή ιδιότητες προϊόντων. Χρησιμοποίησε ΜΟΝΟ όσα δίνονται.",
    `ΓΩΝΙΑ ΤΗΣ ΚΑΜΠΑΝΙΑΣ: ${angle.label}. ${angle.brief}`,
    "",
    "Επίστρεψε ΑΚΡΙΒΩΣ πέντε γραμμές, με αυτή τη σειρά και τίποτα άλλο:",
    "1. Θέμα email — έως 55 χαρακτήρες, να διαβάζεται κομμένο στα 40 σε κινητό",
    "2. Preheader — έως 100 χαρακτήρες, ΣΥΜΠΛΗΡΩΝΕΙ το θέμα, δεν το επαναλαμβάνει",
    "3. Επικεφαλίδα — έως 45 χαρακτήρες, ΚΕΦΑΛΑΙΑ ΧΩΡΙΣ ΤΟΝΟΥΣ (τα ελληνικά κεφαλαία δεν παίρνουν τόνο)",
    "4. Τίτλος hero — έως 40 χαρακτήρες, μία σύντομη φράση",
    "5. Κείμενο — 2 προτάσεις, έως 180 χαρακτήρες συνολικά",
    "",
    "Χωρίς αρίθμηση, χωρίς ετικέτες, χωρίς εισαγωγικά. Μία γραμμή ανά στοιχείο.",
  ].join("\n");

  const user = brief(input.products, input.validUntil);
  const raw = await chat(system, user, 700);

  const lines = raw
    .split("\n")
    .map(clean)
    .filter((l) => l.length > 0);

  /*
   * Το μοντέλο μερικές φορές δίνει τέσσερις ή έξι γραμμές. Δεν πετάμε ό,τι
   * ήρθε: ο συντάκτης βλέπει ό,τι παρήχθη και συμπληρώνει το υπόλοιπο, που
   * είναι πολύ λιγότερος κόπος από το να ξαναζητήσει.
   */
  return {
    subject: lines[0] ?? "",
    preheader: lines[1] ?? "",
    eyebrow: lines[2] ?? "",
    title: lines[3] ?? "",
    text: lines.slice(4).join(" ") || "",
  };
}
