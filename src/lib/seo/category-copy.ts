import { grossAmount } from "@/lib/format";
import { FREE_SHIPPING_THRESHOLD_NET } from "@/lib/cart/options";
import type { FaqPair } from "@/lib/seo/product-faq";
import type { PlpFacets } from "@/lib/catalog/plp-options";

/**
 * Τι λέει μια σελίδα κατηγορίας, πέρα από τα πλακίδια.
 *
 * ── Γιατί ΔΕΝ γράφεται με το χέρι ───────────────────────────────────────────
 *
 * Το `Category` δεν έχει πεδίο περιγραφής, και η προσθήκη ενός θα σήμαινε ότι
 * κάποιος πρέπει να γράψει κείμενο για 23 ρίζες, 33 ομάδες και 187 υποομάδες —
 * και να το ξαναγράψει κάθε φορά που αλλάζει ο κατάλογος. Κείμενο γραμμένο μια
 * φορά και ξεχασμένο γίνεται ψέμα: «μεγάλη ποικιλία σε FESTOOL» σε κατηγορία
 * που δεν έχει πια ούτε ένα FESTOOL.
 *
 * ── Γιατί ΔΕΝ είναι το συνηθισμένο γέμισμα ─────────────────────────────────
 *
 * «Ανακαλύψτε τη μεγάλη μας γκάμα σε ποιοτικά εργαλεία» δεν λέει τίποτα, και
 * αυτό είναι το πρότυπο κείμενο κατηγορίας σε κάθε eshop. Δεν βοηθά αγοραστή,
 * δεν παρατίθεται από μοντέλο, και το Google το αναγνωρίζει από το 2011.
 *
 * Ό,τι γράφεται εδώ είναι μετρημένο: πόσα προϊόντα, πόσα σε απόθεμα, ΠΟΙΕΣ
 * μάρκες υπάρχουν όντως εδώ και με πόσους κωδικούς, από πού ως πού πάνε οι
 * τιμές. Αυτά τα ρωτάει άνθρωπος πριν κάνει scroll, και αυτά παραθέτει ένα
 * μοντέλο όταν ρωτηθεί «πού βρίσκω κρουστικά κατσαβίδια στην Ελλάδα».
 *
 * Ενημερώνεται μόνο του, γιατί διαβάζει τα ίδια facets που τροφοδοτούν τα
 * φίλτρα δίπλα.
 */

/**
 * Ευρώ όπως γράφονται στα ελληνικά: τελεία για τις χιλιάδες.
 *
 * «16590 €» είναι αριθμός που πρέπει να μετρήσει κανείς με το δάχτυλο. Δεν
 * μπαίνουν λεπτά — σε εύρος κατηγορίας τα λεπτά δηλώνουν ακρίβεια που το εύρος
 * δεν έχει.
 */
const eur = (n: number) => `${Math.round(n).toLocaleString("el-GR")} €`;

/**
 * Τα ονόματα κατηγοριών ΔΕΝ πεζογραφούνται. Ποτέ.
 *
 * Στη βάση είναι κεφαλαία και ΑΤΟΝΑ — «ΕΡΓΑΛΕΙΑ ΧΕΙΡΟΣ», «ΚΑΤΣΑΒΙΔΙΑ» — γιατί
 * τα ελληνικά κεφαλαία δεν φέρουν τόνο. Το `toLowerCase()` πάνω τους δίνει
 * «εργαλεια χειρος» και «κατσαβιδια»: ανορθόγραφα. Το είδα να παράγεται και
 * είναι χειρότερο από καθόλου κείμενο — μια σελίδα που γράφει λάθος τη γλώσσα
 * της χάνει τον αναγνώστη πριν φτάσει στο νόημα, και ένα μοντέλο που την
 * παραθέτει διαδίδει το λάθος.
 *
 * Ο τονισμός δεν ανακτάται με κανόνα· θα χρειαζόταν λεξικό. Οπότε τα ονόματα
 * μένουν όπως είναι, μέσα σε εισαγωγικά όπου χρειάζεται, και η πρόταση χτίζεται
 * γύρω τους ώστε τα κεφαλαία να διαβάζονται σαν αναφορά και όχι σαν φωνή.
 */

/** Ένωση ονομάτων με «και» στο τέλος, όπως τα λέει άνθρωπος. */
function joinGreek(items: string[]): string {
  if (items.length <= 1) return items[0] ?? "";
  return `${items.slice(0, -1).join(", ")} και ${items[items.length - 1]}`;
}

export type CategoryCopyInput = {
  name: string;
  total: number;
  facets: PlpFacets;
};

/**
 * Το εύρος τιμών, ρητά ως ΛΙΑΝΙΚΗ με ΦΠΑ.
 *
 * Τα `priceBounds` είναι καθαρές τιμές, στρογγυλοποιημένες προς τα κάτω. Σε
 * κατηγορία με αναλώσιμα το κάτω όριο πέφτει στο μηδέν — μια μύτη των 0,83 €
 * γίνεται 0 — και «από 0 €» είναι πρόταση που δεν λέει τίποτα. Εκεί μένει μόνο
 * το πάνω όριο, που παραμένει αληθές.
 *
 * Ένας συνεργάτης βλέπει στα πλακίδια τις δικές του τιμές, οπότε ένα εύρος
 * χωρίς ετικέτα θα διάβαζε σαν αντίφαση με ό,τι έχει μπροστά του. Η λέξη
 * «λιανικής» λύνει τη διαφορά αντί να την κρύψει.
 */
function priceSentence(facets: PlpFacets): string | null {
  const { min, max } = facets.priceBounds;
  if (max <= 0 || max <= min) return null;
  const hi = eur(grossAmount(max));
  return min >= 1
    ? `Οι τιμές λιανικής ξεκινούν από ${eur(grossAmount(min))} και φτάνουν τα ${hi} με ΦΠΑ.`
    : `Οι τιμές λιανικής φτάνουν έως ${hi} με ΦΠΑ.`;
}

/**
 * Η εισαγωγική παράγραφος — ή τίποτα.
 *
 * Κατηγορία με δύο προϊόντα δεν χρειάζεται κείμενο που περιγράφει δύο προϊόντα:
 * τα βλέπει κανείς ολόκληρα χωρίς scroll. Κάτω από το κατώφλι η παράγραφος
 * παραλείπεται, αντί να γραφτεί κάτι για να μην είναι κενό το σημείο.
 */
export function categoryIntro(input: CategoryCopyInput): string | null {
  const { name, total, facets } = input;
  if (total < 4) return null;

  const inStock =
    facets.availability.find((a) => a.slug === "in-stock")?.count ?? 0;
  const brands = facets.brands.filter((b) => b.count > 0).slice(0, 6);
  const kids = facets.subcategories.filter((c) => c.count > 0).slice(0, 5);

  const parts: string[] = [];

  parts.push(
    inStock > 0
      ? `Στην κατηγορία «${name}» υπάρχουν ${total} κωδικοί, από τους οποίους ${inStock} είναι άμεσα διαθέσιμοι για παραλαβή από το κατάστημα στον Πειραιά ή αποστολή αυθημερόν.`
      : `Στην κατηγορία «${name}» υπάρχουν ${total} κωδικοί, οι οποίοι αυτή τη στιγμή προμηθεύονται κατόπιν παραγγελίας.`,
  );

  if (brands.length >= 2) {
    parts.push(
      `Οι μάρκες που καλύπτονται εδώ είναι ${joinGreek(
        brands.map((b) => `${b.label} (${b.count})`),
      )}.`,
    );
  }

  const price = priceSentence(facets);
  if (price) parts.push(price);

  if (kids.length >= 2) {
    parts.push(`Περιλαμβάνει: ${joinGreek(kids.map((c) => c.label))}.`);
  }

  parts.push(
    `Τα μεταφορικά είναι δωρεάν για παραγγελίες άνω των ${FREE_SHIPPING_THRESHOLD_NET} € (καθαρή αξία).`,
  );

  return parts.join(" ");
}

/**
 * Οι ερωτήσεις που αφορούν την κατηγορία, όχι το μεμονωμένο προϊόν.
 *
 * Ξεχωριστές από τις ερωτήσεις της σελίδας προϊόντος: εκεί ρωτιέται «έχει
 * εγγύηση αυτό;», εδώ «τι μάρκες έχετε σε αυτό;». Ίδιος κανόνας — καμία
 * ερώτηση χωρίς το δεδομένο που την απαντά.
 */
export function categoryFaq(input: CategoryCopyInput): FaqPair[] {
  const { name, total, facets } = input;
  if (total < 4) return [];

  const pairs: FaqPair[] = [];
  const inStock =
    facets.availability.find((a) => a.slug === "in-stock")?.count ?? 0;
  const brands = facets.brands.filter((b) => b.count > 0).slice(0, 8);

  if (brands.length >= 2) {
    pairs.push({
      q: `Τι μάρκες έχετε στην κατηγορία «${name}»;`,
      a:
        `Στην κατηγορία «${name}» διαθέτουμε ${joinGreek(brands.map((b) => b.label))}. ` +
        `Είμαστε επίσημος αντιπρόσωπος, οπότε τα προϊόντα συνοδεύονται από την εγγύηση του κατασκευαστή ` +
        `και όχι από εγγύηση παράλληλης εισαγωγής.`,
    });
  }

  if (inStock > 0) {
    pairs.push({
      q: `Πόσα προϊόντα από «${name}» είναι άμεσα διαθέσιμα;`,
      a:
        `${inStock} από τους ${total} κωδικούς είναι σε απόθεμα αυτή τη στιγμή. ` +
        `Παραγγελία πριν τις 15:00 εργάσιμη αποστέλλεται αυθημερόν με ACS, ` +
        `ή μπορείτε να την παραλάβετε από το κατάστημα στον Πειραιά σε περίπου δύο ώρες. ` +
        `Το φίλτρο «Άμεσα διαθέσιμα» δείχνει μόνο αυτά.`,
    });
  }

  const price = priceSentence(facets);
  if (price) {
    pairs.push({
      q: `Πόσο κοστίζουν τα προϊόντα στην κατηγορία «${name}»;`,
      a:
        `${price.replace(/\.$/, "")}, ανάλογα με τη μάρκα και τα χαρακτηριστικά. ` +
        `Τα μεταφορικά είναι δωρεάν άνω των ${FREE_SHIPPING_THRESHOLD_NET} € καθαρής αξίας. ` +
        `Οι εταιρικοί πελάτες έχουν χονδρική τιμολόγηση μετά την έγκριση του λογαριασμού τους.`,
    });
  }

  return pairs;
}

/**
 * Ερωτήσεις και απαντήσεις για μια σελίδα μάρκας.
 *
 * ── Γιατί μια μάρκα χρειάζεται δικές της ───────────────────────────────────
 *
 * «Είναι επίσημος αντιπρόσωπος ο Κολλέρης για τη Bosch;» και «έχει εγγύηση;»
 * είναι οι δύο ερωτήσεις που κρίνουν την αγορά επαγγελματικού εργαλείου, και
 * μια μηχανή απάντησης δεν έχει από πού να τις απαντήσει: η σελίδα το λέει σε
 * τρέχον κείμενο, όχι σε δομή. Γραμμένες εδώ, γίνονται παραθέσιμες — και
 * είναι το ίδιο κείμενο που διαβάζει ο επισκέπτης, όχι ξεχωριστό markup που
 * αποκλίνει.
 *
 * ── Κατώφλι, όπως και στις κατηγορίες ──────────────────────────────────────
 *
 * Κάτω από τέσσερις κωδικούς δεν βγαίνει FAQ: «έχουμε 2 προϊόντα Χ» δεν είναι
 * απάντηση σε τίποτα, και ένα `FAQPage` με μια κενή ερώτηση είναι θόρυβος που
 * κοστίζει στην αξιοπιστία του υπόλοιπου structured data.
 */
export function brandFaq(input: {
  name: string;
  total: number;
  inStock: number;
  categories?: string[];
}): FaqPair[] {
  const { name, total, inStock } = input;
  if (total < 4) return [];

  const pairs: FaqPair[] = [
    {
      q: `Είστε επίσημος αντιπρόσωπος ${name};`,
      a:
        `Ναι. Είμαστε επίσημος διανομέας ${name} στην Ελλάδα και προμηθευόμαστε απευθείας ` +
        `από τον κατασκευαστή. Τα προϊόντα συνοδεύονται από την εγγύηση του κατασκευαστή ` +
        `και όχι από εγγύηση παράλληλης εισαγωγής, και τα ανταλλακτικά είναι γνήσια.`,
    },
    {
      q: `Πόσα προϊόντα ${name} έχετε;`,
      a:
        `Ο κατάλογος έχει ${total.toLocaleString("el-GR")} κωδικούς ${name}` +
        (inStock > 0
          ? `, από τους οποίους ${inStock.toLocaleString("el-GR")} είναι σε απόθεμα αυτή τη στιγμή. ` +
            `Το φίλτρο «Άμεσα διαθέσιμα» δείχνει μόνο αυτά.`
          : `. Η διαθεσιμότητα ενημερώνεται από την αποθήκη κάθε δέκα λεπτά.`),
    },
    {
      q: `Πότε θα παραλάβω μια παραγγελία ${name};`,
      a:
        `Ό,τι είναι σε απόθεμα και παραγγελθεί πριν τις 15:00 εργάσιμη αποστέλλεται αυθημερόν ` +
        `με ACS — παράδοση σε 24-48 ώρες σε όλη την Ελλάδα. Εναλλακτικά μπορείτε να το ` +
        `παραλάβετε από το κατάστημα στον Πειραιά σε περίπου δύο ώρες.`,
    },
  ];

  if (input.categories && input.categories.length >= 2) {
    pairs.push({
      q: `Σε ποιες κατηγορίες έχετε προϊόντα ${name};`,
      a: `Τα προϊόντα ${name} του καταλόγου μας καλύπτουν ${joinGreek(input.categories.slice(0, 8))}.`,
    });
  }

  return pairs;
}
