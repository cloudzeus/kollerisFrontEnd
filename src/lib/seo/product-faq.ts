import { FREE_SHIPPING_THRESHOLD_NET } from "@/lib/cart/options";

/**
 * Οι ερωτήσεις που ρωτάει κάποιος πριν αγοράσει ένα εργαλείο — απαντημένες από
 * τα δεδομένα του ίδιου του προϊόντος.
 *
 * ── Τι είναι AEO, και τι ΔΕΝ κερδίζει αυτό ─────────────────────────────────
 *
 * Να ειπωθεί καθαρά, γιατί η αντίθετη εντύπωση κυκλοφορεί: από τον Αύγουστο του
 * 2023 το Google ΔΕΝ εμφανίζει πια FAQ rich results για εμπορικούς ιστότοπους —
 * μόνο για κυβερνητικούς και υγείας. Αυτό εδώ δεν πρόκειται να βγάλει
 * πτυσσόμενες ερωτήσεις κάτω από το αποτέλεσμα αναζήτησης, και όποιος το
 * υπόσχεται πουλάει κάτι που το Google κατάργησε.
 *
 * Αυτό που ΟΝΤΩΣ κερδίζει είναι το άλλο μισό: τα μοντέλα. Όταν κάποιος ρωτά ένα
 * AI «έχει εγγύηση αυτό το κατσαβίδι» ή «πότε θα μου έρθει», η απάντηση
 * συντίθεται από πηγές που δηλώνουν ερώτηση και απάντηση σε ζεύγος. Πρόζα που
 * περιέχει την ίδια πληροφορία απαιτεί από το μοντέλο να τη βρει· ένα
 * `FAQPage` του τη δίνει. Το ίδιο ισχύει για φωνητική αναζήτηση, όπου η
 * απάντηση διαβάζεται φωναχτά και πρέπει να στέκει μόνη της.
 *
 * ── Κανένα ζεύγος δεν επινοείται ───────────────────────────────────────────
 *
 * Κάθε ερώτηση παράγεται ΜΟΝΟ όταν υπάρχει το δεδομένο που την απαντά. Προϊόν
 * χωρίς δηλωμένη εγγύηση δεν αποκτά ερώτηση εγγύησης — δεν παίρνει «δεν
 * διατίθεται», γιατί αυτό είναι απάντηση που κανείς δεν έθεσε και ισχυρισμός
 * που κανείς δεν έλεγξε. Λιγότερες ερωτήσεις με αληθινές απαντήσεις είναι
 * καλύτερη πηγή από πολλές με κενά.
 *
 * Οι απαντήσεις κρατιούνται κοντά στις 40-60 λέξεις: είναι το μήκος που ένα
 * μοντέλο παραθέτει ολόκληρο και μια φωνητική συσκευή διαβάζει χωρίς να κόψει.
 */

export type FaqPair = { q: string; a: string };

export type FaqProduct = {
  name: string;
  sku: string;
  brandName: string | null;
  inStock: boolean;
  qty: number;
  guaranteeMonths: number | null;
  priceGross: number | null;
  specs: Array<{ label: string; value: string; unit: string | null }>;
};

const money = (n: number) => `${n.toFixed(2).replace(".", ",")} €`;

/**
 * Πώς αναφέρεται ένα εργαλείο σε ερώτηση.
 *
 * Το όνομα του ERP είναι «1/2" ΚΑΡΥΔΑΚΙΑ & ΕΞΑΡΤΗΜΑΤΑ ΕΝΘΕΤΟ ΑΦΡΟΥ SET 70τμχ
 * 4932480716» — σωστό ως τίτλος, αδύνατο ως ερώτηση. Κανείς δεν ρωτά «πόση
 * εγγύηση έχει το 1/2" ΚΑΡΥΔΑΚΙΑ & ΕΞΑΡΤΗΜΑΤΑ…», και μια φωνητική συσκευή που
 * το διαβάζει φωναχτά έξι φορές είναι βασανιστήριο.
 *
 * Οι επαγγελματίες αναφέρονται σε εργαλεία με μάρκα και κωδικό: «το MILWAUKEE
 * 4932480716». Αυτό είναι και το ερώτημα που πληκτρολογείται. Χωρίς μάρκα ή
 * κωδικό μοντέλου, το όνομα κόβεται σε κάτι που στέκει σε πρόταση.
 */
function askLabel(product: FaqProduct): string {
  const model = product.specs
    .find((s) => /μοντέλ|model/i.test(s.label))
    ?.value?.trim();
  if (product.brandName && model) return `${product.brandName} ${model}`;
  if (product.brandName) return `${product.brandName} ${product.sku}`;
  return product.name.length > 48
    ? `${product.name.slice(0, 45).trimEnd()}…`
    : product.name;
}

/**
 * Πόσοι μήνες σε ανθρώπινη μορφή.
 *
 * «24 μήνες» και «2 χρόνια» είναι το ίδιο, αλλά κανείς δεν ρωτά «πόσους μήνες
 * εγγύηση» για κάτι διετές. Η μονάδα ακολουθεί τον τρόπο που ρωτιέται.
 */
function guaranteeText(months: number): string {
  if (months % 12 === 0) {
    const years = months / 12;
    return years === 1 ? "ένα έτος" : `${years} έτη`;
  }
  return `${months} μήνες`;
}

export function productFaq(product: FaqProduct): FaqPair[] {
  const pairs: FaqPair[] = [];
  const label = askLabel(product);

  /* Διαθεσιμότητα — η πρώτη ερώτηση κάθε αγοραστή, και η μόνη που αλλάζει ώρα με την ώρα. */
  pairs.push({
    q: `Είναι διαθέσιμο το ${label};`,
    a: product.inStock
      ? `Ναι. Το ${label} (κωδικός ${product.sku}) είναι άμεσα διαθέσιμο από το κατάστημά μας στον Πειραιά. ` +
        `Παραγγελία πριν τις 15:00 εργάσιμη αποστέλλεται αυθημερόν, και μπορείτε να το παραλάβετε και από το κατάστημα.`
      : `Αυτή τη στιγμή το ${label} (κωδικός ${product.sku}) δεν είναι σε απόθεμα. ` +
        `Το προμηθευόμαστε κατόπιν παραγγελίας — επικοινωνήστε μαζί μας για χρόνο παράδοσης.`,
  });

  /* Εγγύηση — μόνο όταν υπάρχει δηλωμένη. */
  if (product.guaranteeMonths && product.guaranteeMonths > 0) {
    pairs.push({
      q: `Πόση εγγύηση έχει το ${label};`,
      a:
        `Το ${label} καλύπτεται με εγγύηση ${guaranteeText(product.guaranteeMonths)} ` +
        `${product.brandName ? `από την ${product.brandName}` : "από τον κατασκευαστή"}. ` +
        `Η εγγύηση καλύπτει κατασκευαστικά ελαττώματα και δεν καλύπτει φυσιολογική φθορά από χρήση.`,
    });
  }

  /* Τιμή — μόνο όταν υπάρχει τιμή· προϊόν χωρίς τιμή δεν πουλιέται online. */
  if (product.priceGross != null && product.priceGross > 0) {
    pairs.push({
      q: `Πόσο κοστίζει το ${label};`,
      a:
        `Η τιμή είναι ${money(product.priceGross)} με ΦΠΑ. ` +
        `Τα μεταφορικά είναι δωρεάν για παραγγελίες άνω των ${FREE_SHIPPING_THRESHOLD_NET} € (καθαρή αξία), ` +
        `και η παραλαβή από το κατάστημα στον Πειραιά είναι πάντα χωρίς χρέωση.`,
    });
  }

  /*
   * Χαρακτηριστικά — μόνο τα μετρήσιμα, και μόνο αν είναι αρκετά για απάντηση.
   *
   * Δύο χαρακτηριστικά δεν κάνουν απάντηση· κάνουν πρόταση που θα μπορούσε να
   * είναι στην περιγραφή. Το κατώφλι είναι τρία.
   */
  /*
   * Μόνο τα ΜΕΤΡΗΣΙΜΑ.
   *
   * Ίδιο φίλτρο με το `additionalProperty`: «Κατασκευαστής MILWAUKEE, Κατηγορία
   * Εργαλειοθήκη» δεν είναι απάντηση στο «ποια είναι τα χαρακτηριστικά» — είναι
   * η ταυτότητα, που ήδη λέει η ερώτηση. Απάντηση που επαναλαμβάνει την ερώτηση
   * είναι χειρότερη από απουσία απάντησης.
   */
  const IDENTITY =
    /^(κατασκευαστ|μάρκα|brand|μοντέλ|model|κατηγορ|υποκατηγορ)/i;
  const measurable = product.specs
    .filter((s) => s.label?.trim() && s.value?.trim())
    .filter((s) => !IDENTITY.test(s.label.trim()))
    .slice(0, 6);
  if (measurable.length >= 3) {
    pairs.push({
      q: `Ποια είναι τα χαρακτηριστικά του ${label};`,
      a:
        `${label}: ` +
        measurable
          .map((s) => `${s.label} ${s.value}${s.unit ? ` ${s.unit}` : ""}`)
          .join(", ") +
        ".",
    });
  }

  /* Παράδοση και επιστροφή — ίδια για κάθε προϊόν, και ρωτιούνται για κάθε προϊόν. */
  pairs.push({
    q: `Πόσο γρήγορα θα παραλάβω το ${label};`,
    a:
      `Παραγγελία πριν τις 15:00 εργάσιμη φεύγει αυθημερόν με ACS. ` +
      `Στην Αττική παραδίδεται την επόμενη εργάσιμη, στην ηπειρωτική Ελλάδα σε 1-2 εργάσιμες ` +
      `και στα νησιά σε 2-3. Από το κατάστημα στον Πειραιά είναι έτοιμο σε περίπου δύο ώρες.`,
  });

  pairs.push({
    q: `Μπορώ να επιστρέψω το ${label};`,
    a:
      `Ναι. Έχετε δικαίωμα υπαναχώρησης 14 ημερολογιακών ημερών από την παραλαβή, ` +
      `εφόσον το προϊόν επιστραφεί στην αρχική του συσκευασία και σε κατάσταση που επιτρέπει τη μεταπώληση. ` +
      `Επικοινωνήστε μαζί μας για να οργανώσουμε την επιστροφή.`,
  });

  return pairs;
}

/**
 * Τα ζεύγη ως `FAQPage`.
 *
 * Χτίζεται από ΤΟΝ ΙΔΙΟ πίνακα που αποδίδει η σελίδα — ό,τι δηλώνεται στη
 * μηχανή είναι ό,τι διαβάζει ο επισκέπτης. Schema που λέει κάτι που η σελίδα
 * δεν δείχνει είναι παράβαση των οδηγιών του Google, όχι έξυπνη κίνηση.
 */
export function faqJsonLd(pairs: FaqPair[]) {
  if (pairs.length === 0) return undefined;
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: pairs.map((p) => ({
      "@type": "Question",
      name: p.q,
      acceptedAnswer: { "@type": "Answer", text: p.a },
    })),
  };
}
