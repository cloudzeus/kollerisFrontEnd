/**
 * Πόσο μεγαλώνει το λογότυπο μιας μάρκας μέσα στο κουτί του.
 *
 * ── Γιατί χρειάζεται καθόλου ──────────────────────────────────────────────
 *
 * Τα λογότυπα έρχονται από το HDCtool ως τετράγωνα με το σήμα «letterboxed»
 * μέσα σε διαφανή περιθώρια — αλλά το πόσα περιθώρια έχει το καθένα δεν το
 * ορίζει κανείς: εξαρτάται από το αρχείο που έστειλε ο κατασκευαστής. Το
 * KARNASCH είναι 95% διαφανές, το BESSEY 47%. Στο ίδιο κουτί των 64px, το
 * πρώτο φαίνεται μισό από το δεύτερο, παρότι και τα δύο «γεμίζουν» το κουτί.
 *
 * Η πληροφορία δεν υπάρχει πουθενά στα δεδομένα και δεν μπορεί να υπολογιστεί
 * στον διακομιστή χωρίς να διαβαστεί κάθε εικόνα. Ώσπου τα αρχεία να κοπούν
 * στην πηγή τους, αυτός ο πίνακας είναι η διόρθωση — μικρός, ρητός, και με
 * προεπιλογή το 1 ώστε καμία μάρκα να μη χρειάζεται καταχώριση.
 *
 * ── Πότε ΝΑ ΜΗΝ προστεθεί μάρκα εδώ ───────────────────────────────────────
 *
 * Αν ένα λογότυπο δείχνει μικρό επειδή ΕΙΝΑΙ μικρό σήμα (ένα σύμβολο δίπλα σε
 * λεκτικά σήματα), μεγεθύνοντάς το το κάνει να ξεχωρίζει χωρίς λόγο. Εδώ
 * μπαίνουν μόνο αρχεία με υπερβολικά περιθώρια.
 */
const LOGO_SCALE: Record<string, number> = {
  /* 95% διαφανή εικονοστοιχεία — το σήμα πιάνει το ένα τρίτο του τετραγώνου. */
  karnasch: 1.35,
  nitecore: 1.35,
};

/** Πολλαπλασιαστής μεγέθους για το λογότυπο, 1 όταν δεν χρειάζεται διόρθωση. */
export function logoScaleFor(slug: string): number {
  return LOGO_SCALE[slug] ?? 1;
}

/**
 * Έτοιμο στυλ για το `<Image>` του λογοτύπου.
 *
 * `scale` και όχι μεγαλύτερο πλάτος: το κουτί μένει στο ίδιο μέγεθος σε όλο το
 * πλέγμα — αλλιώς μία μάρκα θα έσπρωχνε τις διπλανές της.
 */
export function logoScaleStyle(slug: string): { transform?: string } {
  const scale = logoScaleFor(slug);
  return scale === 1 ? {} : { transform: `scale(${scale})` };
}
