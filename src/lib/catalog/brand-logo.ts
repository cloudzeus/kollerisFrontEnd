/**
 * Διορθώσεις τοποθέτησης για λογότυπα μαρκών.
 *
 * ── Γιατί χρειάζεται καθόλου ──────────────────────────────────────────────
 *
 * Τα λογότυπα έρχονται από το HDCtool ως τετράγωνα 600×600 με το σήμα
 * «letterboxed» μέσα σε διαφανή περιθώρια. Το `object-contain` κεντράρει το
 * ΤΕΤΡΑΓΩΝΟ — άρα το σήμα φαίνεται σωστό μόνο αν είναι κεντραρισμένο μέσα στο
 * τετράγωνο, και σε σωστή κλίμακα ως προς αυτό. Ούτε το ένα ούτε το άλλο
 * εγγυάται κανείς: εξαρτάται από το αρχείο που έστειλε ο κατασκευαστής.
 *
 * Μέτρησα το πλαίσιο των μη-διαφανών εικονοστοιχείων και στα 43 λογότυπα του
 * καταλόγου. Ένα μόνο δεν είναι κεντραρισμένο, και δύο έχουν σήμα τόσο πλατύ
 * και χαμηλό που στο ίδιο τετράγωνο κουτί διαβάζονται μισά από τα υπόλοιπα.
 *
 * ── Η σωστή λύση δεν είναι εδώ ────────────────────────────────────────────
 *
 * Είναι να κοπούν τα αρχεία στην πηγή τους, στο HDCtool, ώστε το σήμα να
 * γεμίζει το τετράγωνο. Μέχρι τότε αυτός ο πίνακας είναι η διόρθωση: μικρός,
 * ρητός, με προεπιλογή «τίποτα» ώστε καμία μάρκα να μη χρειάζεται καταχώριση.
 *
 * ── Πότε ΝΑ ΜΗΝ προστεθεί μάρκα εδώ ───────────────────────────────────────
 *
 * Αν ένα λογότυπο δείχνει μικρό επειδή ΕΙΝΑΙ μικρό σήμα — ένα σύμβολο δίπλα σε
 * λεκτικά σήματα — μεγεθύνοντάς το το κάνει να ξεχωρίζει χωρίς λόγο. Εδώ
 * μπαίνουν μόνο αρχεία με μετρημένο πρόβλημα τοποθέτησης.
 */
type LogoFix = {
  /** Πολλαπλασιαστής μεγέθους. */
  scale?: number;
  /** Κατακόρυφη μετατόπιση ως ποσοστό του ύψους — αρνητικό = προς τα πάνω. */
  offsetY?: number;
};

const LOGO_FIX: Record<string, LogoFix> = {
  /*
   * Το σήμα κάθεται 21% ΧΑΜΗΛΟΤΕΡΑ από το κέντρο μέσα στο ίδιο του το αρχείο
   * (μετρημένο πλαίσιο: κέντρο στο 0,71 του ύψους αντί για 0,50). Είναι το
   * μόνο από τα 43 που δεν είναι κεντραρισμένο, και γι' αυτό δεν στοίχιζε με
   * τα διπλανά του.
   */
  bessey: { offsetY: -20.9 },

  /*
   * Σήματα πλατιά και χαμηλά: γεμίζουν το πλάτος του τετραγώνου αλλά ελάχιστο
   * από το ύψος του, οπότε σε τετράγωνο κουτί το ορατό σήμα βγαίνει μικρό.
   */
  /*
   * 1,12 και όχι 1,35 όπως αρχικά. Ο τοίχος των μαρκών κρατά πλέον 20px
   * περιθώριο γύρω από κάθε λογότυπο, και το `transform: scale()` μεγαλώνει
   * ΠΑΝΩ από το κουτί — στο 1,35 τα δύο αυτά σήματα έτρωγαν το μισό περιθώριο
   * και ακουμπούσαν σχεδόν τη γραμμή του πλακιδίου. Στο 1,12 η διόρθωση
   * εξακολουθεί να πιάνει (το σήμα τους είναι πλατύ και χαμηλό) χωρίς να
   * σπάει τον κανόνα του κουτιού.
   */
  karnasch: { scale: 1.12 },
  nitecore: { scale: 1.12 },
};

/**
 * Έτοιμο στυλ για το `<Image>` του λογοτύπου, ή κενό όταν δεν χρειάζεται.
 *
 * `transform` και όχι διαφορετικές διαστάσεις: το κουτί μένει ίδιο σε όλο το
 * πλέγμα — αλλιώς μία μάρκα θα έσπρωχνε τις διπλανές της.
 */
export function logoScaleStyle(slug: string): { transform?: string } {
  const fix = LOGO_FIX[slug];
  if (!fix) return {};
  const parts: string[] = [];
  if (fix.offsetY) parts.push(`translateY(${fix.offsetY}%)`);
  if (fix.scale) parts.push(`scale(${fix.scale})`);
  return parts.length ? { transform: parts.join(" ") } : {};
}
