/**
 * Το όνομα χωρίς το νούμερο.
 *
 * Στη λίστα η κάρτα εκπροσωπεί ΟΛΗ την ομάδα, οπότε «FLEXTRED NUBUCK S3S
 * ΠΑΠΟΥΤΣΙ ΑΣΦΑΛΕΙΑΣ No 36 …» λέει ψέματα: το προϊόν δεν είναι το 36, είναι το
 * παπούτσι. Και στη σελίδα, ο επιλογέας από κάτω δείχνει ήδη ποιο νούμερο είναι
 * επιλεγμένο — ο τίτλος που το επαναλαμβάνει είναι θόρυβος.
 *
 * ── Δύο φρένα ─────────────────────────────────────────────────────────────
 *
 * Αφαιρείται ΜΟΝΟ όταν το προϊόν ανήκει σε ομάδα, και ΜΟΝΟ η ετικέτα που έχει
 * ανατεθεί σε αυτόν τον κωδικό. Ένα τυφλό «κόψε το No <αριθμός>» θα χάλαγε το
 * «ΚΛΕΙΔΙ ΠΙΠΑΣ No 12», όπου το 12 ΕΙΝΑΙ το προϊόν — και αυτά τα προϊόντα δεν
 * ανήκουν ποτέ σε ομάδα ακριβώς γι' αυτόν τον λόγο.
 *
 * Το «No» μπροστά φεύγει μαζί, αλλιώς μένει ορφανό στη μέση της πρότασης.
 *
 * Το όνομα δεν αλλάζει στο καλάθι, στην παραγγελία ή στο email: εκεί το νούμερο
 * είναι ΤΟ βασικό στοιχείο του τι αγοράστηκε.
 */
export function nameWithoutSize(
  name: string,
  options: { variantGroup?: string | null; sizeLabel?: string | null },
): string {
  const label = options.sizeLabel?.trim();
  if (!options.variantGroup || !label) return name;

  const escaped = label.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const cleaned = name
    .replace(new RegExp(`(^|\\s)(No\\s+)?${escaped}(?=\\s|$)`, "i"), " ")
    .replace(/\s+/g, " ")
    .trim();

  // Αν έμεινε σχεδόν τίποτα, το αρχικό όνομα ήταν κυρίως το νούμερο — καλύτερα
  // ένα όνομα με το νούμερο μέσα παρά μια κάρτα χωρίς όνομα.
  return cleaned.length >= 3 ? cleaned : name;
}
