/**
 * Πόσο απόθεμα δείχνουμε στον πελάτη.
 *
 * Ο ακριβής αριθμός είναι χρήσιμος μόνο όταν είναι ΜΙΚΡΟΣ: «2 τεμ.» λέει
 * «αποφάσισε τώρα» και είναι ο λόγος που κάποιος πατάει αγορά. «47 τεμ.» δεν
 * λέει τίποτα στον αγοραστή και λέει πολλά στον ανταγωνιστή — το απόθεμά μας
 * ανά κωδικό είναι εμπορική πληροφορία, και η βιτρίνα το έδινε δωρεάν σε κάθε
 * σελίδα, κάρτα και πρόταση αναζήτησης.
 *
 * Το όριο είναι τρία: στα τρία και κάτω γράφουμε τον αριθμό, από τέσσερα και
 * πάνω γράφουμε «Διαθέσιμο».
 *
 * Ένα σημείο και όχι πέντε: η ίδια απόφαση χρειάζεται στη σελίδα προϊόντος,
 * στην κάρτα, στη γρήγορη προβολή, στην αναζήτηση και στις προτάσεις. Πέντε
 * αντίγραφα σημαίνει ότι το επόμενο όριο θα αλλάξει σε τέσσερα από αυτά.
 */

/** Πάνω από αυτό δεν αποκαλύπτεται ποσότητα. */
export const STOCK_EXACT_MAX = 3;

/** Δείχνουμε ακριβή αριθμό; Μόνο για μικρά, θετικά αποθέματα. */
export function showsExactQty(qty: number | null | undefined): boolean {
  const n = Number(qty ?? 0);
  return Number.isFinite(n) && n > 0 && n <= STOCK_EXACT_MAX;
}
