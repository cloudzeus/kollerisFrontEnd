"use client";

import { useEffect, useRef } from "react";

/**
 * Κείμενο που χωράει στο κελί του.
 *
 * ── Τι έσπαγε ──────────────────────────────────────────────────────────────
 *
 * Το κελί αποδίδεται με `overflow-hidden` — πρέπει, αλλιώς μια φωτογραφία
 * `cover` θα ξεχείλιζε πάνω στο διπλανό κελί. Άρα ό,τι δεν χωράει δεν
 * ξεχειλίζει: ΚΟΒΕΤΑΙ. Μια τιμή «337,71 €» σε κουτί 40% έχανε το «€», και
 * ένας τίτλος που έπιανε τέσσερις γραμμές αντί για τρεις έχανε την τελευταία.
 *
 * Το ύπουλο είναι ότι εξαρτάται από πράγματα που κανείς δεν αλλάζει επίτηδες:
 * το πλήθος των στηλών, τη γλώσσα (τα ελληνικά είναι ~15% πλατύτερα από τα
 * αγγλικά), το μήκος του ονόματος ενός προϊόντος που ήρθε από το ERP. Η
 * σύνθεση φαινόταν σωστή όταν φτιάχτηκε και έσπασε μόνη της αργότερα.
 *
 * ── Γιατί δεν λύνεται με CSS ───────────────────────────────────────────────
 *
 * Οι ρόλοι δίνουν ήδη `clamp()`, που κλιμακώνει με το ΠΛΑΤΟΣ του κελιού. Αυτό
 * που λείπει είναι το ύψος: πόσες γραμμές έπιασε το κείμενο τελικά. Κανένας
 * υπολογισμός CSS δεν το ξέρει αυτό πριν στοιχειοθετηθεί — μόνο μέτρηση μετά.
 *
 * ── Πώς προσαρμόζεται ──────────────────────────────────────────────────────
 *
 * Μηδενίζει το inline μέγεθος, αφήνει τον ρόλο να πει το ιδανικό, μετράει ως
 * προς το ΚΕΛΙ — όχι ως προς το κουτί του layer, που δεν κόβει τίποτα και
 * είναι απλώς το σημείο όπου το τράβηξε ο συντάκτης — και κατεβάζει 8% τη φορά
 * μέχρι να χωρέσει, με δάπεδο στο 55%: κάτω από εκεί το κείμενο έχει ήδη πάψει
 * να διαβάζεται και το πρόβλημα είναι η σύνθεση,
 * όχι το μέγεθος. Ξανατρέχει σε κάθε αλλαγή διαστάσεων και όταν φορτώσουν οι
 * γραμματοσειρές: πριν φτάσει η Roboto Flex, το κείμενο μετριέται σε άλλη
 * γραμματοσειρά και η μέτρηση δεν ισχύει.
 *
 * ── Ο διακομιστής γράφει το σωστό μέγεθος ──────────────────────────────────
 *
 * Το `clamp()` του ρόλου αποδίδεται από τον διακομιστή· αυτό εδώ μόνο το
 * μειώνει όταν χρειάζεται. Αν η JavaScript δεν τρέξει ποτέ, το banner είναι
 * ακριβώς ό,τι ήταν πριν — όχι άδειο, όχι σε λάθος μέγεθος.
 */
export function FitText({ children }: { children: React.ReactNode }) {
  const ref = useRef<HTMLSpanElement>(null);

  useEffect(() => {
    const span = ref.current;
    /* Το κελί, που είναι και το μόνο που κόβει. Το κουτί του ίδιου του layer
       δεν κόβει τίποτα — είναι σημείο αγκύρωσης, όχι πλαίσιο. */
    const clip = span?.closest(".bn-clip");
    if (!span || !clip) return;

    let frame = 0;

    const fit = () => {
      /* Πίσω στο μέγεθος του ρόλου πριν από κάθε μέτρηση. Χωρίς αυτό, ένα
         κελί που ΜΕΓΑΛΩΣΕ θα κρατούσε τη συρρίκνωση του προηγούμενου. */
      span.style.fontSize = "";

      const cell = clip.getBoundingClientRect();
      if (!cell.width || !cell.height) return;

      const ideal = Number.parseFloat(getComputedStyle(span).fontSize);
      if (!Number.isFinite(ideal) || ideal <= 0) return;

      const floor = ideal * 0.55;
      let size = ideal;
      /* Φραγμένος βρόχος: ~8% τη φορά, 12 βήματα φτάνουν ως το δάπεδο. Ένα
         `while` χωρίς μετρητή πάνω σε μέτρηση διάταξης είναι πάγωμα σελίδας
         την ημέρα που κάποιο κουτί βγει μηδενικό. */
      for (let step = 0; step < 12; step += 1) {
        const r = span.getBoundingClientRect();
        const outside =
          r.left < cell.left - 0.5 ||
          r.right > cell.right + 0.5 ||
          r.top < cell.top - 0.5 ||
          r.bottom > cell.bottom + 0.5;
        if (!outside || size <= floor) break;
        size = Math.max(floor, size * 0.92);
        span.style.fontSize = `${size}px`;
      }
    };

    const schedule = () => {
      cancelAnimationFrame(frame);
      frame = requestAnimationFrame(fit);
    };

    const observer = new ResizeObserver(schedule);
    observer.observe(clip);
    schedule();
    document.fonts?.ready.then(schedule).catch(() => {});

    return () => {
      observer.disconnect();
      cancelAnimationFrame(frame);
    };
  }, [children]);

  return (
    <span ref={ref} className="block">
      {children}
    </span>
  );
}
