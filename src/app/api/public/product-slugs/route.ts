import { NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";

/**
 * Ο χάρτης `MTRL → slug`, για όποιον χτίζει συνδέσμους προς το κατάστημα.
 *
 * ── Γιατί υπάρχει ─────────────────────────────────────────────────────────
 *
 * Το HDCtool παράγει το feed του Skroutz, αλλά δεν έχει slug — τα παράγει το
 * κατάστημα, από το όνομα και τον κωδικό, με κανόνες που ζουν εδώ. Μέχρι τώρα
 * το feed έστελνε τους αγοραστές σε σελίδα του ίδιου του HDCtool: τίτλος «HDC
 * Tools», μια τιμή, και κανένα κουμπί εκτός από «Home». Πληρωμένο κλικ σε
 * αδιέξοδο.
 *
 * Η εναλλακτική ήταν να μάθει το HDCtool να φτιάχνει slug μόνο του. Δύο
 * γεννήτριες για το ίδιο πράγμα διαφωνούν στην πρώτη αλλαγή κανόνα, και η
 * διαφωνία εμφανίζεται ως 404 σε διαφήμιση που πληρώνεται.
 *
 * ── Δεν είναι ευαίσθητο ───────────────────────────────────────────────────
 *
 * Κάθε slug εδώ βρίσκεται ήδη στο δημόσιο sitemap. Αυτό που ΔΕΝ βγαίνει είναι
 * τιμές, αποθέματα και εσωτερικά αναγνωριστικά: ο καταναλωτής αυτού του
 * endpoint χτίζει συνδέσμους, δεν χρειάζεται τίποτα άλλο.
 *
 * ── Μόνο ενεργά ───────────────────────────────────────────────────────────
 *
 * Ένα ανενεργό προϊόν δεν έχει σελίδα. Αν έλειπε αυτό το φίλτρο, το feed θα
 * διαφήμιζε διευθύνσεις που επιστρέφουν 404 — χειρότερο από το αδιέξοδο που
 * αντικαθιστά.
 */

/*
 * Δυναμικό, όχι `revalidate`: με `revalidate` το Next το προ-αποδίδει στο build,
 * όπου η βάση δεν είναι προσβάσιμη, και το deploy αποτυγχάνει. Ο κατάλογος
 * αλλάζει με ρυθμό ωρών, οπότε την κρυφή μνήμη την κρατά το cache-control.
 */
export const dynamic = "force-dynamic";

export async function GET() {
  const rows = await prisma.product.findMany({
    where: { isActive: true },
    select: { mtrl: true, slug: true },
    orderBy: { mtrl: "asc" },
  });

  return NextResponse.json(
    {
      count: rows.length,
      generatedAt: new Date().toISOString(),
      /* Αντικείμενο και όχι πίνακας: ο καταναλωτής ψάχνει ανά MTRL. */
      slugs: Object.fromEntries(rows.map((r) => [r.mtrl, r.slug])),
    },
    { headers: { "cache-control": "public, max-age=900, s-maxage=900" } },
  );
}
